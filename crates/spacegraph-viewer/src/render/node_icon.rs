    fn icons_have_no_steady_state_churn() {
        let mut app = App::new();
        app.insert_resource(graph_state(150))
            .insert_resource(NodeIcons::default())
            .insert_resource(dummy_icon_resources())
            .insert_resource(DetailCapability::Mid)
            .add_systems(Update, sync_node_icons);
        spawn_camera(&mut app);

        app.update();
        let frame1 = icon_entities(&mut app);
        assert!(!frame1.is_empty());
        app.update();
        let frame2 = icon_entities(&mut app);
        assert_eq!(frame1, frame2, "steady state must not respawn icons");
    }
