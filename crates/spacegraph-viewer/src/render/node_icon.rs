    #[test]
    fn file_subtype_maps_extensions() {
        assert_eq!(file_subtype("/home/a/pic.PNG"), IconId::FileImage);
        assert_eq!(file_subtype("/v/clip.mp4"), IconId::FileVideo);
        assert_eq!(file_subtype("/m/song.flac"), IconId::FileAudio);
        assert_eq!(file_subtype("/src/main.rs"), IconId::FileCode);
        assert_eq!(file_subtype("/etc/app.json"), IconId::FileJson);
        assert_eq!(file_subtype("/var/log/sys.log"), IconId::FileLog);
        assert_eq!(file_subtype("/doc/readme.md"), IconId::FileText);
        assert_eq!(file_subtype("/a/backup.tar.gz"), IconId::FileArchive);
        assert_eq!(file_subtype("/usr/lib/libc.so"), IconId::FileBinary);
        // No extension and dotfiles → generic.
        assert_eq!(file_subtype("/etc/passwd"), IconId::FileGeneric);
        assert_eq!(file_subtype("/home/u/.bashrc"), IconId::FileGeneric);
    }

    #[test]
    fn icon_for_dispatches_node_kinds() {
        use spacegraph_core::Node;
        assert_eq!(
            icon_for(&Node::Process {
                pid: 1,
                ppid: 0,
                exe: "x".into(),
                cmdline: "x".into(),
                uid: 0
            }),
            IconId::Process
        );
        assert_eq!(
            icon_for(&Node::File {
                path: "/a/b.png".into(),
                inode: 1,
                kind: FileKind::Regular
            }),
            IconId::FileImage
        );
        // A directory is generic regardless of any extension-like name.
        assert_eq!(
            icon_for(&Node::File {
                path: "/a/b.png".into(),
                inode: 1,
                kind: FileKind::Dir
            }),
            IconId::FileGeneric
        );
    }

    #[test]
    fn atlas_alpha_is_a_cutout_mask() {
        // The committed atlas must be a real cutout: its alpha channel is bimodal —
        // fully-transparent background texels AND opaque glyph texels. With the
        // `AlphaMode::Mask` material below this guards that icons render a glyph
        // cutout, not a filled quad (the "big green block" bug). GPU confirmation is
        // a local step in this headless env.
        let alphas: Vec<u8> = ATLAS_BYTES.iter().skip(3).step_by(4).copied().collect();
        assert_eq!(alphas.len(), (ATLAS_SIZE * ATLAS_SIZE) as usize);
        let transparent = alphas.iter().filter(|&&a| a == 0).count();
        let opaque = alphas.iter().filter(|&&a| a == 255).count();
        assert!(
            transparent > 0,
            "atlas must have transparent background texels"
        );
        assert!(opaque > 0, "atlas must have opaque glyph texels");
        assert!(
            transparent > opaque,
            "glyph is a sparse cutout, not a filled block"
        );
    }

    #[test]
    fn glyph_material_is_alpha_masked_with_nearest_atlas() {
        let mut app = App::new();
        app.add_plugins((MinimalPlugins, bevy::asset::AssetPlugin::default()))
            .init_asset::<Image>()
            .init_asset::<Mesh>()
            .init_asset::<StandardMaterial>()
            .add_systems(Startup, setup_node_icon_resources);
        app.update();

        let res = app.world().resource::<NodeIconResources>();
        let mats = app.world().resource::<Assets<StandardMaterial>>();
        let images = app.world().resource::<Assets<Image>>();
        // Every textured glyph material masks (opaque-pass cutout), not opaque fill.
        for h in res.glyph_mat.iter() {
            let m = mats.get(h).expect("glyph material present");
            assert!(
                matches!(m.alpha_mode, AlphaMode::Mask(_)),
                "glyph material must alpha-mask the cutout"
            );
        }
        // The atlas carries an explicit (nearest) sampler so the mask edge is crisp
        // (per-fragment alpha 0/1), not the linear default that blurs thin strokes.
        let atlas = images.get(&res.atlas).expect("atlas image present");
        assert!(
            matches!(atlas.sampler, ImageSampler::Descriptor(_)),
            "atlas must use an explicit sampler (nearest), not the linear default"
        );
    }

    #[test]
    fn icon_half_extent_is_clamped_to_node_scale() {
        for kind in theme::NodeKind::ALL {
            let h = icon_half_extent(kind);
            assert!(
                h <= ICON_HALF_MAX + f32::EPSILON,
                "{kind:?} exceeds the cap"
            );
            assert!(
                h >= ICON_HALF_MIN - f32::EPSILON,
                "{kind:?} too small to read"
            );
            // Never overhangs the node core (the "big block" bug).
            assert!(
                h <= node_envelope(kind) + 1e-4,
                "{kind:?} icon must fit within the node envelope"
            );
        }
        // A larger node carries a larger-or-equal glyph.
        assert!(
            icon_half_extent(theme::NodeKind::Alert) >= icon_half_extent(theme::NodeKind::File)
        );
    }

    #[test]
    fn icon_cells_are_unique_and_in_range() {
        let mut seen = std::collections::HashSet::new();
        for icon in IconId::ALL {
            let c = icon.cell();
            assert!(c < ICON_COUNT as u32);
            assert!(seen.insert(c), "duplicate atlas cell {c}");
        }
    }

    #[test]
    fn icons_share_one_atlas_and_quad_set() {
        // Structural perf proxy: a single atlas handle, and every textured glyph
        // material references that same handle (no per-node texture/material).
        let mut app = App::new();
        app.add_plugins((MinimalPlugins, bevy::asset::AssetPlugin::default()))
            .init_asset::<Image>()
            .init_asset::<Mesh>()
            .init_asset::<StandardMaterial>()
            .add_systems(Startup, setup_node_icon_resources);
        app.update();

        let res = app.world().resource::<NodeIconResources>();
        let mats = app.world().resource::<Assets<StandardMaterial>>();
        assert_eq!(res.quad.len(), ICON_COUNT);
        for h in res.glyph_mat.iter() {
            let m = mats.get(h).expect("glyph material present");
            assert_eq!(
                m.base_color_texture.as_ref(),
                Some(&res.atlas),
                "all glyph materials must share the single atlas handle"
            );
        }
        // Flat (Low) materials are untextured colour chips.
        for h in res.flat_mat.iter() {
            let m = mats.get(h).expect("flat material present");
            assert!(m.base_color_texture.is_none());
        }
    }

