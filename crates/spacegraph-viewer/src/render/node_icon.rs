//! Level-1 node-face icons (v0.4.1) — a type/file-subtype glyph on **every**
//! visible node, drawn as a billboarded quad sampling one shared atlas.
//!
//! Cost is O(visible) and allocation-free in steady state: a single atlas
//! texture, one quad mesh per glyph cell (a fixed set, not per-node), and a
//! small per-kind material set — all shared across nodes (Bevy GPU-instances
//! entities with identical mesh+material). Icons are tier-independent (always on,
//! cheap), matching the v0.5.0 gate-glyph split (`docs/spec_v0.5.0.md` §2.3); on
//! `Low` they use a flat colour variant instead of the textured glyph.
//!
//! **v0.5.0 seam:** this face glyph is the *centre* of v0.5.0's gate-glyph unit
//! (WP-2: concentric ring + centre icon), and the centre that the radial command
//! HUD (WP-3) will wrap.

